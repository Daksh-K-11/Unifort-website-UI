'use client'

import React, { useState, useEffect, useCallback, useMemo } from 'react'
import {
  ShieldAlert,
  Search,
  Lock,
  Clock,
  Terminal,
  Activity,
  Code,
  X,
  RefreshCw,
} from 'lucide-react'
import { useAdminAuth } from '../admin-auth-context'
import { AuditLogRecord } from '../admin-types'
import { api } from '../../../lib/api-client'

export function AuditLogsView() {
  const { canViewAuditLogs } = useAdminAuth()

  const [logs, setLogs] = useState<AuditLogRecord[]>([])
  const [loading, setLoading] = useState(true)
  const [actionFilter, setActionFilter] = useState<string>('ALL')
  const [searchQuery, setSearchQuery] = useState('')
  const [inspectingLog, setInspectingLog] = useState<AuditLogRecord | null>(null)

  const fetchLogs = useCallback(async () => {
    if (!canViewAuditLogs) return
    setLoading(true)
    try {
      const res = await api.get('/admin/audit-logs', {}, true)
      if (res.success && res.data) {
        const raw = Array.isArray(res.data) ? res.data : (res.data.logs || [])
        const mapped: AuditLogRecord[] = raw.map((l: any) => ({
          id: l.id,
          action: l.action,
          resource: l.resource || undefined,
          details: l.details,
          ipAddress: l.ipAddress || '127.0.0.1',
          userId: l.userId,
          userEmail: l.userEmail,
          userRole: l.userRole,
          user: l.user
            ? {
                name: `${l.user.firstName || ''} ${l.user.lastName || ''}`.trim() || l.user.email,
                email: l.user.email,
                role: l.user.role,
              }
            : undefined,
          createdAt: l.createdAt,
        }))
        setLogs(mapped)
      }
    } catch (e) {
      console.error('Failed to load audit logs', e)
    } finally {
      setLoading(false)
    }
  }, [canViewAuditLogs])

  useEffect(() => {
    fetchLogs()
  }, [fetchLogs])

  const formatLogSummary = (log: AuditLogRecord): string => {
    if (log.resource) return log.resource
    if (typeof log.details === 'string') return log.details
    if (log.details && typeof log.details === 'object') {
      if (log.details.url) {
        return `${log.details.method || 'ACTION'} ${log.details.url}`
      }
      return JSON.stringify(log.details)
    }
    return '—'
  }

  // Dynamic filter tabs based on recorded actions
  const actionTabs = useMemo(() => {
    const set = new Set<string>()
    logs.forEach((l) => {
      if (l.action) set.add(l.action)
    })
    return ['ALL', ...Array.from(set)]
  }, [logs])

  const filteredLogs = useMemo(() => {
    const q = searchQuery.trim().toLowerCase()
    return logs.filter((l) => {
      const matchesAction = actionFilter === 'ALL' || l.action === actionFilter
      if (!matchesAction) return false
      if (!q) return true

      const summary = formatLogSummary(l).toLowerCase()
      const actionStr = l.action.toLowerCase()
      const userName = (l.user?.name || '').toLowerCase()
      const userEmail = (l.user?.email || l.userEmail || '').toLowerCase()
      const ip = (l.ipAddress || '').toLowerCase()

      return (
        actionStr.includes(q) ||
        summary.includes(q) ||
        userName.includes(q) ||
        userEmail.includes(q) ||
        ip.includes(q)
      )
    })
  }, [logs, actionFilter, searchQuery])

  if (!canViewAuditLogs) {
    return (
      <div className="p-12 rounded-2xl adm-card border border-red-500/20 flex flex-col items-center justify-center text-center">
        <div className="w-12 h-12 rounded-2xl bg-red-500/10 border border-red-500/30 flex items-center justify-center mb-3">
          <Lock className="w-6 h-6 text-red-500 dark:text-red-400" />
        </div>
        <h3 className="text-base font-serif font-medium adm-text-primary">403 Forbidden — Access Denied</h3>
        <p className="text-xs adm-text-muted mt-1 max-w-sm">
          Cryptographic security audit trails and forensic logs are restricted strictly to the Master{' '}
          <code className="text-purple-600 dark:text-purple-300 font-mono">ADMIN</code> role.
        </p>
      </div>
    )
  }

  return (
    <div className="space-y-6">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h2 className="text-xl font-serif tracking-tight adm-text-primary font-medium">
            Cryptographic Security Audit Logs
          </h2>
          <p className="text-xs adm-text-muted mt-0.5">
            Immutable log trail generated by the backend audit interceptor on sensitive state modifications.
          </p>
        </div>

        <button
          type="button"
          onClick={fetchLogs}
          disabled={loading}
          className="px-3.5 py-2 rounded-xl text-xs font-medium adm-card border adm-border adm-text-primary hover:bg-[#424a70]/10 flex items-center gap-1.5 self-start sm:self-auto cursor-pointer transition-colors"
        >
          <RefreshCw className={`w-3.5 h-3.5 ${loading ? 'animate-spin' : ''}`} />
          <span>Refresh Trail</span>
        </button>
      </div>

      {/* Filter and Search Bar */}
      <div className="adm-card border rounded-2xl p-4 flex flex-col md:flex-row items-stretch md:items-center justify-between gap-3 shadow-sm">
        <div className="flex flex-wrap items-center gap-1.5 overflow-x-auto pb-1 md:pb-0 scrollbar-none">
          {actionTabs.map((act) => (
            <button
              key={act}
              type="button"
              onClick={() => setActionFilter(act)}
              className={`px-3 py-1.5 rounded-lg text-xs font-medium whitespace-nowrap transition-all cursor-pointer ${
                actionFilter === act
                  ? 'tab-active bg-[#424a70] !text-white [&_*]:!text-white shadow-sm'
                  : 'adm-text-muted hover:adm-text-primary hover:bg-black/5 dark:hover:bg-white/5'
              }`}
            >
              {act === 'ALL' ? 'All Actions' : act.replace(/_/g, ' ')}
            </button>
          ))}
        </div>

        <div className="relative min-w-[240px]">
          <Search className="w-3.5 h-3.5 adm-text-muted absolute left-3 top-1/2 -translate-y-1/2" />
          <input
            type="text"
            value={searchQuery}
            onChange={(e) => setSearchQuery(e.target.value)}
            placeholder="Search action, resource, operator, IP..."
            className="w-full pl-9 pr-3 py-1.5 adm-input border rounded-xl text-xs adm-text-primary focus:outline-none focus:border-[#424a70] transition-colors"
          />
        </div>
      </div>

      {/* Table or Empty State */}
      {loading ? (
        <div className="p-12 rounded-2xl adm-card border flex flex-col items-center justify-center text-center shadow-sm">
          <div className="w-8 h-8 rounded-full border-2 border-[#424a70] border-t-transparent animate-spin mb-3" />
          <p className="text-xs adm-text-muted">Loading cryptographic audit events...</p>
        </div>
      ) : filteredLogs.length === 0 ? (
        <div className="p-12 rounded-2xl adm-card border flex flex-col items-center justify-center text-center shadow-sm">
          <div className="w-12 h-12 rounded-2xl bg-purple-500/10 border border-purple-500/20 flex items-center justify-center mb-3">
            <ShieldAlert className="w-6 h-6 text-purple-500 dark:text-purple-400" />
          </div>
          <h3 className="text-base font-medium adm-text-primary">No Audit Events Logged</h3>
          <p className="text-xs adm-text-muted mt-1 max-w-sm">
            {searchQuery
              ? `No audit entries matched "${searchQuery}".`
              : 'As staff and administrators perform state changes (updating order statuses, modifying kiln notes, or updating roles), cryptographically verifiable entries stream here.'}
          </p>
        </div>
      ) : (
        <div className="adm-card border rounded-2xl overflow-hidden shadow-sm">
          <table className="w-full text-left border-collapse">
            <thead>
              <tr className="border-b adm-border adm-table-head text-[10px] uppercase tracking-wider adm-text-muted font-medium">
                <th className="py-3 px-4">Action Hook</th>
                <th className="py-3 px-4">Target Resource / Context</th>
                <th className="py-3 px-4">Operator</th>
                <th className="py-3 px-4">Origin IP</th>
                <th className="py-3 px-4 text-right">Timestamp</th>
                <th className="py-3 px-4 text-right">Payload</th>
              </tr>
            </thead>
            <tbody className="divide-y adm-border text-xs adm-text-secondary font-mono">
              {filteredLogs.map((log) => (
                <tr key={log.id} className="adm-table-hover transition-colors">
                  <td className="py-3 px-4">
                    <span className="inline-flex items-center text-[10px] px-2 py-0.5 rounded-full bg-purple-500/15 border border-purple-400/30 text-purple-600 dark:text-purple-300 font-medium">
                      {log.action}
                    </span>
                  </td>
                  <td className="py-3 px-4 max-w-sm truncate adm-text-primary font-sans text-xs not-italic">
                    {formatLogSummary(log)}
                  </td>
                  <td className="py-3 px-4 adm-text-secondary font-sans not-italic">
                    <span className="font-medium adm-text-primary block">
                      {log.user?.name || log.userEmail || 'System'}
                    </span>
                    <span className="text-[10px] adm-text-muted">
                      {log.user?.role || log.userRole || 'SERVICE'}
                    </span>
                  </td>
                  <td className="py-3 px-4 adm-text-muted text-[11px] font-mono">
                    {log.ipAddress}
                  </td>
                  <td className="py-3 px-4 text-right adm-text-muted text-[11px] font-mono whitespace-nowrap">
                    {new Date(log.createdAt).toLocaleDateString()}{' '}
                    {new Date(log.createdAt).toLocaleTimeString()}
                  </td>
                  <td className="py-3 px-4 text-right">
                    <button
                      type="button"
                      onClick={() => setInspectingLog(log)}
                      className="p-1.5 rounded-lg border adm-border hover:bg-[#424a70]/10 text-[#424a70] dark:text-[#8b97d1] transition-colors cursor-pointer"
                      title="Inspect full JSON cryptographic payload"
                    >
                      <Code className="w-3.5 h-3.5" />
                    </button>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}

      {/* JSON Payload Inspection Modal */}
      {inspectingLog && (
        <div className="fixed inset-0 adm-modal-overlay backdrop-blur-sm z-50 flex items-center justify-center p-4">
          <div className="w-full max-w-2xl adm-modal-bg border rounded-2xl shadow-2xl overflow-hidden flex flex-col max-h-[85vh]">
            <div className="p-4 border-b adm-border flex items-center justify-between">
              <div>
                <span className="text-[10px] uppercase tracking-wider text-purple-600 dark:text-purple-300 font-semibold font-mono">
                  {inspectingLog.action}
                </span>
                <h3 className="text-sm font-medium adm-text-primary mt-0.5">
                  Audit Entry Forensics: {inspectingLog.id}
                </h3>
              </div>
              <button
                type="button"
                onClick={() => setInspectingLog(null)}
                className="p-1.5 rounded-lg adm-text-muted hover:adm-text-primary cursor-pointer"
              >
                <X className="w-4 h-4" />
              </button>
            </div>

            <div className="p-4 overflow-y-auto space-y-3 font-mono text-xs">
              <div className="grid grid-cols-2 gap-2 text-[11px] p-3 rounded-xl bg-black/5 dark:bg-white/5 border adm-border">
                <div>
                  <span className="adm-text-muted block text-[10px] uppercase">Operator</span>
                  <span className="adm-text-primary">
                    {inspectingLog.user?.name || inspectingLog.userEmail} ({inspectingLog.user?.role || inspectingLog.userRole})
                  </span>
                </div>
                <div>
                  <span className="adm-text-muted block text-[10px] uppercase">Client IP Address</span>
                  <span className="adm-text-primary">{inspectingLog.ipAddress}</span>
                </div>
                <div>
                  <span className="adm-text-muted block text-[10px] uppercase">Resource Target</span>
                  <span className="adm-text-primary">{inspectingLog.resource || '—'}</span>
                </div>
                <div>
                  <span className="adm-text-muted block text-[10px] uppercase">Timestamp</span>
                  <span className="adm-text-primary">{inspectingLog.createdAt}</span>
                </div>
              </div>

              <div>
                <span className="text-[10px] uppercase tracking-wider adm-text-muted font-semibold block mb-1">
                  Full Captured Payload
                </span>
                <pre className="p-4 rounded-xl bg-black/90 text-emerald-400 overflow-x-auto text-[11px] leading-relaxed max-h-72 border border-black/40">
                  {JSON.stringify(inspectingLog.details || { note: 'No supplementary payload captured' }, null, 2)}
                </pre>
              </div>
            </div>

            <div className="p-3 border-t adm-border flex items-center justify-end">
              <button
                type="button"
                onClick={() => setInspectingLog(null)}
                className="px-4 py-1.5 rounded-xl text-xs adm-btn-primary cursor-pointer"
              >
                Close Forensics
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  )
}
